import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
const transport = new StdioClientTransport({ command: "node", args: [new URL("../dist/index.js", import.meta.url).pathname], env: { ...process.env } });
const client = new Client({ name: "test", version: "1" });
await client.connect(transport);
console.log("TOOLS", (await client.listTools()).tools.map((t) => t.name).join(", "));
console.log("PROMPTS", (await client.listPrompts()).prompts.map((p) => p.name).join(", "));
const list = await client.callTool({ name: "talkcontext_list_sessions", arguments: {} });
console.log("LIST\n" + list.content[0].text);
const session = await client.callTool({ name: "talkcontext_get_session", arguments: {} });
console.log("SESSION (start)\n" + session.content[0].text.slice(0, 400));
const fb = await client.callTool({ name: "talkcontext_get_feedback", arguments: { item: "F1" } });
for (const c of fb.content) console.log("F1 content:", c.type, c.type === "text" ? c.text.slice(0, 160).replace(/\n/g, " ⏎ ") : `${c.mimeType} ${c.data.length} base64`);
const logs = await client.callTool({ name: "talkcontext_get_logs", arguments: { kind: "network" } });
console.log("LOGS", logs.content[0].text.slice(0, 300));
const bad = await client.callTool({ name: "talkcontext_get_feedback", arguments: { item: "F9" } });
console.log("BAD", bad.isError, bad.content[0].text);
await client.close();
